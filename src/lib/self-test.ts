export function scoreTest(answers: number[]) {
  if (answers.length !== 24 || answers.some(a => !Number.isInteger(a) || a < 1 || a > 5)) throw new Error("Ответь на все 24 утверждения");
  const scores = answers.map((a, i) => REVERSED_QUESTIONS.includes(i + 1) ? 6 - a : a);
  return TEST_GROUPS.map(g => ({ ...g, value: scores.slice(g.start, g.end).reduce((a,b) => a+b, 0) / (g.end-g.start) }));
}
// At shared endpoints, the higher band wins: 2 is movement, 4 is resource.
export function profileBand(value: number) {
  return value >= 4 ? "Ресурс — опора" : value >= 2 ? "Здесь есть движение" : "Зона Тени";
}
export function suggestedLevel(answers: number[]): "soft" | "medium" {
  return Math.min(...scoreTest(answers).map(s => s.value)) < 3 ? "soft" : "medium";
}
